def _ae(s: str) -> str:
    return html.escape(s or "", quote=False)

LANG_COOKIE = "ui_lang"
VALID = frozenset({"cs", "en"})


def normalize_lang(code: Optional[str]) -> str:
    if not code:
        return "cs"
    c = str(code).strip().lower()[:2]
    return c if c in VALID else "cs"


def get_lang(request: Request) -> str:
    return normalize_lang(request.cookies.get(LANG_COOKIE))


def html_lang_attr(lang: str) -> str:
    return "en" if normalize_lang(lang) == "en" else "cs"


def next_path_from_request(request: Request) -> str:
    p = request.url.path
    if request.url.query:
        p += "?" + request.url.query
    return p


def quote_next(path: str) -> str:
    return quote(path if path.startswith("/") else "/", safe="/?:=&")


